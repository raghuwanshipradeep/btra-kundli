def _format_degree(value) -> str:
    try:
        return f"{float(value):.4f}"
    except (TypeError, ValueError):
        return str(value)


def _safe_time(value) -> str:
    if value is None or value == "" or str(value).lower() == "nan":
        return "—"
    s = str(value).strip()
    if "nan" in s.lower():
        return "—"
    if ":" in s:
        parts = s.split(":")
        try:
            return ":".join(f"{int(p):02d}" for p in parts)
        except ValueError:
            return s
    return s


