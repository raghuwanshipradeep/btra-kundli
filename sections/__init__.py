def build_sign_planet_map(
    planets: list,
    lang: str = "en",
) -> dict[str, list[str]]:
    short = PLANET_SHORT_HI if lang == "hi" else PLANET_SHORT_EN
    result: dict[str, list[str]] = {}
    for p in planets:
        name = p.name if hasattr(p, "name") else p.get("name", "")
        sign = p.sign if hasattr(p, "sign") else p.get("sign", "")
        is_retro = (p.isRetro if hasattr(p, "isRetro") else p.get("isRetro", "false"))
        abbr = short.get(name)
        if not abbr or not sign:
            continue
        if is_retro == "true" and name != "Ascendant":
            abbr += "(R)" if lang != "hi" else "(व)"
        result.setdefault(sign, []).append(abbr)
    return result


def get_north_indian_sign_for_house(house_number: int, lagna_sign_id: int) -> int:
    return ((lagna_sign_id - 1 + house_number - 1) % 12) + 1


def translate_keys(data: dict | list | None, key_map: dict[str, str]) -> dict | list | None:
    if data is None:
        return None
    if isinstance(data, list):
        return [translate_keys(item, key_map) if isinstance(item, (dict, list)) else item for item in data]
    if isinstance(data, dict):
        return {key_map.get(k, k): translate_keys(v, key_map) if isinstance(v, (dict, list)) else v for k, v in data.items()}
    return data


